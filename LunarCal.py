# ------------------------------------------------------------
# 取得某農曆年 y 的「閏月月份」
# - 回傳 0：表示該年沒有閏月
# - 回傳 1~12：表示閏該月（例如回傳 4 表示閏四月）
# ------------------------------------------------------------
def leap_month(y: int) -> int:
    return lunarInfo[y - 1900] & 0xF

# ------------------------------------------------------------
# 取得某農曆年 y 的「閏月天數」
# - 沒有閏月：回傳 0
# - 有閏月：依 0x10000 位元判斷 29 或 30 天
# ------------------------------------------------------------
def leap_days(y: int) -> int:
    lm = leap_month(y)
    if lm:
        return 30 if (lunarInfo[y - 1900] & 0x10000) else 29
    return 0

# ------------------------------------------------------------
# 取得某農曆年 y、月 m（1~12）的天數
# - 依位元表中對應月份的 bit 判斷 29/30 天
# - (0x10000 >> m) 是常見取該月 bit 的方式
# ------------------------------------------------------------
def month_days(y: int, m: int) -> int:
    return 30 if (lunarInfo[y - 1900] & (0x10000 >> m)) else 29

# ------------------------------------------------------------
# 取得某農曆年 y 的「全年總天數」
# - 基礎 12 個月，每月先假設 29 天：12*29 = 348
# - 再把大月（30天的月）逐個加 1 天
# - 最後再加上閏月天數（若有）
# ------------------------------------------------------------
def year_days(y: int) -> int:
    info = lunarInfo[y - 1900]
    total = 348

    # 從 0x8000 開始對 12 個月做位元檢查（對應月份大小月資訊）
    mask = 0x8000
    for _ in range(12):
        if info & mask:
            total += 1
        mask >>= 1
    return total + leap_days(y)

# ------------------------------------------------------------
# 基準日：1900-01-31 對應農曆 1900/01/01（此演算法常用基準）
# 之後只要算出「從農曆 1900/01/01 到目標農曆日期」的偏移天數，
# 加回 base_date 就能得到公曆日期。
# ------------------------------------------------------------
base_date = date(1900, 1, 31)

# ------------------------------------------------------------
# 核心：農曆 -> 公曆
# 參數：
# - y: 農曆年
# - m: 農曆月 (1~12)
# - d: 農曆日 (1~30)
# - is_leap: 是否指定「閏月」(True 表示閏 m 月)
#
# 作法：
# 1) 把 1900 到 (y-1) 的整年天數全部加總（跨年）
# 2) 把 y 年中 1 月到 (m-1) 月的天數加總（跨月）
#    若該年在某月後面有閏月，還要把閏月天數加上
# 3) 若指定 is_leap=True，表示要落在「閏 m 月」：
#    - 需確認該年閏月就是 m
#    - 先把同月的「正月」天數跨過，才進入閏月
# 4) 再加上 (d-1)（跨日），最後換算成公曆日期
# ------------------------------------------------------------
def lunar_to_solar(y: int, m: int, d: int, is_leap: bool = False) -> date:
    # 參數基本檢查（避免輸入明顯錯誤）
    if y < 1900 or y > 2100:
        raise ValueError("year 必須在 1900~2100 範圍內")
    if m < 1 or m > 12:
        raise ValueError("month 必須在 1~12")
    if d < 1 or d > 30:
        raise ValueError("day 必須在 1~30")

    offset = 0

    # (1) 先跨過 1900~(y-1) 的天數
    for yy in range(1900, y):
        offset += year_days(yy)

    # (2) 再跨過 y 年的 1~(m-1) 月
    lm = leap_month(y)  # 該年閏月月份（0 表示無）
    for mm in range(1, m):
        offset += month_days(y, mm)

        # 如果該年閏月是 mm，則「正 mm 月」後面還有一個閏 mm 月
        # 所以要把閏月天數也加上（因為目標月份在後面）
        if lm and mm == lm:
            offset += leap_days(y)

    # (3) 如果指定要「閏 m 月」
    if is_leap:
        if lm != m:
            raise ValueError("指定為閏月但該年無此閏月")

        # 要到閏月，必須先跨過同月份的正月天數
        offset += month_days(y, m)  # 先跨過同月的「正月」天數再進入閏月

    # (4) 跨到該月的第 d 天（d-1 表示從月初起算的偏移）
    offset += (d - 1)

    # 以 base_date 往後加 offset 天
    return base_date + timedelta(days=offset)

# ------------------------------------------------------------
# 輸出用：每行 5 筆，格式完全符合你前面的範例
# ------------------------------------------------------------
def print_5_per_line(title: str, items: list[str]) -> None:
    print(title)
    for i in range(0, len(items), 5):
        chunk = items[i:i+5]
        line = ", ".join(f"'{x}'" for x in chunk)
        # 不是最後一行就加逗號，視覺上更像你給的範例
        if i + 5 < len(items):
            line += ","
        print(line)
    print()

