# 位元表內容（常見解釋）：
# - 低 4 bits (0xF)：閏月月份（0 表示無閏月；1~12 表示閏哪一個月）
# - 第 16 bit (0x10000)：閏月天數（1=30天、0=29天）—僅在有閏月時有意義
# - 中間 12 bits（從 0x8000 往下）：12 個月份大小月資訊
#   - bit=1 表示該月 30 天（大月）
#   - bit=0 表示該月 29 天（小月）
#
# 注意：
# - 這種演算法不是「天文即時推算」，而是用既定表格 + 位元解析來換算日期，
#   對 1900~2100 的範圍通常可用於多數系統需求（節日/排程/比對）。
# ------------------------------------------------------------

